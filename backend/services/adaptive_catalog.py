def seed_catalog():
    for uid, account in ((95001, 'lab5_student'), (95002, 'lab5_peer')):
        if not db.session.get(User, uid):
            db.session.add(User(id=uid, account=account, name='实验学习者（合成）', role='student', password_hash=generate_password_hash('Lab5-demo-2026')))
    for ordinal, (key, (name, desc, questions)) in enumerate(CATALOG.items(), 1):
        if not db.session.get(Skill, key):
            db.session.add(Skill(id=key, name=name, description=desc, ordinal=ordinal))
        course_id = 96000 + ordinal
        if not db.session.get(Course, course_id):
            db.session.add(Course(id=course_id, title=name+'研习（实验）', category=name, description=desc, lesson_count=3, is_active=True))
        db.session.flush()
        for level in (1, 2, 3):
            resource_id = 97000 + ordinal * 10 + level
            selected = questions[(level-1)*2:level*2]
            text = '\n\n'.join(f'{q[0]}\n建议：{q[1]}。\n说明：{q[5]}' for q in selected)
            text += '\n\n练习：以《分数的初步认识》为情境，写出一段教学设计；对照上述原则标注理由，完成技能复测检查理解。'
            if not db.session.get(Resource, resource_id):
                db.session.add(Resource(id=resource_id, title=f'{name}·第{level}级学习卡', category=name, description=desc, is_active=True))
            db.session.flush()
            if not SkillMaterial.query.filter_by(skill_id=key, level=level).first():
                db.session.add(SkillMaterial(skill_id=key, resource_id=resource_id, course_id=course_id, level=level, content=text))
        for index, q in enumerate(questions):
            code = f'{key}-{index+1}'
            if not Question.query.filter_by(code=code).first():
                # Rotate positions so answer keys cannot be inferred from a constant option.
                choices = list(q[1:5]); offset = index % 4
                choices = choices[-offset:] + choices[:-offset] if offset else choices
                db.session.add(Question(code=code, skill_id=key, level=index//2+1, prompt=q[0],
                    options=dict(zip('ABCD', choices)), answer='ABCD'[offset], explanation=q[5], active=True))
    db.session.flush()
